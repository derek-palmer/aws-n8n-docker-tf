#!/usr/bin/env bash
# =============================================================================
# scripts/setup_local_env.sh — Generate .env.local for local development
#
# Runs inside Docker (amazon/aws-cli) via: make setup-local
# No AWS credentials required.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
ENV_FILE="${REPO_ROOT}/.env.local"

# Colours
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
info()    { echo -e "${CYAN}[info]${NC}  $*"; }
success() { echo -e "${GREEN}[ok]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[warn]${NC}  $*"; }

echo ""
echo -e "${CYAN}============================================================${NC}"
echo -e "${CYAN}  n8n Local Environment Setup${NC}"
echo -e "${CYAN}============================================================${NC}"
echo ""
echo -e "${YELLOW}(Press Enter to accept the default shown in brackets)${NC}"
echo ""

# Existing value helper — reads current value from .env.local if it exists
current() {
  local key="$1" default="$2"
  if [[ -f "${ENV_FILE}" ]]; then
    local val
    val=$(grep "^${key}=" "${ENV_FILE}" 2>/dev/null | cut -d= -f2- || true)
    echo "${val:-${default}}"
  else
    echo "${default}"
  fi
}

# --- Use defaults? ---
read -rp "  Use all defaults? [Y/n]: " USE_DEFAULTS
USE_DEFAULTS="${USE_DEFAULTS:-y}"

# --- App config ---
echo ""
echo -e "${CYAN}--- Application ---${NC}"
if [[ "${USE_DEFAULTS}" =~ ^[Nn] ]]; then
  read -rp "  Host     [localhost]: " N8N_HOST;     N8N_HOST="${N8N_HOST:-localhost}"
  read -rp "  Protocol [http]:      " N8N_PROTOCOL; N8N_PROTOCOL="${N8N_PROTOCOL:-http}"
  read -rp "  Port     [5678]:      " N8N_PORT;     N8N_PORT="${N8N_PORT:-5678}"
else
  N8N_HOST="localhost"; N8N_PROTOCOL="http"; N8N_PORT="5678"
  info "Using defaults: ${N8N_PROTOCOL}://${N8N_HOST}:${N8N_PORT}"
fi

echo ""
echo -e "${CYAN}--- Security ---${NC}"
EXISTING_KEY=$(current N8N_ENCRYPTION_KEY "")
if [[ -n "${EXISTING_KEY}" ]]; then
  warn "Existing encryption key found — keeping it (changing this will break saved credentials)."
  N8N_ENCRYPTION_KEY="${EXISTING_KEY}"
else
  N8N_ENCRYPTION_KEY=$(od -vN 32 -A n -t x1 /dev/urandom | tr -d ' \n')
  info "Auto-generated N8N_ENCRYPTION_KEY."
fi

echo ""
echo -e "${CYAN}--- Database ---${NC}"
if [[ "${USE_DEFAULTS}" =~ ^[Nn] ]]; then
  read -rp "  Postgres username [n8n]: " POSTGRES_USER; POSTGRES_USER="${POSTGRES_USER:-n8n}"
  read -rp "  Postgres database [n8n]: " POSTGRES_DB;   POSTGRES_DB="${POSTGRES_DB:-n8n}"
else
  POSTGRES_USER="n8n"; POSTGRES_DB="n8n"
  info "Using defaults: user=${POSTGRES_USER}, db=${POSTGRES_DB}"
fi

EXISTING_PW=$(current POSTGRES_PASSWORD "")
if [[ -n "${EXISTING_PW}" ]]; then
  warn "Existing Postgres password found — keeping it."
  POSTGRES_PASSWORD="${EXISTING_PW}"
else
  POSTGRES_PASSWORD=$(od -vN 16 -A n -t x1 /dev/urandom | tr -d ' \n')
  info "Auto-generated POSTGRES_PASSWORD."
fi

# --- Write .env.local ---
cat > "${ENV_FILE}" <<EOF
# Local development environment — DO NOT COMMIT
# Generated by scripts/setup_local_env.sh — re-run to regenerate.

N8N_HOST=${N8N_HOST}
N8N_PROTOCOL=${N8N_PROTOCOL}
N8N_PORT=${N8N_PORT}
N8N_ENCRYPTION_KEY=${N8N_ENCRYPTION_KEY}

POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
EOF

success "Wrote ${ENV_FILE}"

echo ""
echo -e "${GREEN}============================================================${NC}"
echo -e "${GREEN}  Local env ready! Run: make up-local${NC}"
echo -e "${GREEN}============================================================${NC}"
echo ""
